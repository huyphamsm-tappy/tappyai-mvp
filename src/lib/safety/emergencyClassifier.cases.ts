// Labelled cases for emergencyClassifier.ts. WRITTEN BY THE SAME HAND AS THE CLASSIFIER (11/11): this is an in-sample set, not a held-out one. Its numbers say the rules do what their author meant;
// they do not predict the rate on real traffic. `expect` is the category an EMERGENCY must get, or null when the sentence must NOT fire.
//   emergency = a clear first-person or imminent-danger statement;  near_miss = shares words with an emergency but is past, hypothetical, fiction, a joke or a drill;
//   topic = a question or request ABOUT the subject (hotlines, history, first aid in general);  everyday = an ordinary sentence that happens to contain a trigger word.

