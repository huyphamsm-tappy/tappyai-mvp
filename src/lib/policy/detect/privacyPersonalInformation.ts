/** The registry record, through the sanctioned provider seam. */
export function privacyPolicyRecord(): PolicyRecord {
  const found = defaultPolicyProvider.getById(P1_POLICY_REF);
  if (found.state !== 'FOUND') {
    throw new Error(`P1 pilot: ${P1_POLICY_REF} not available from the provider (${found.state})`);
  }
  return found.record;
}

/**
 * The probe for the Explore observation seam.
 *
 * Carries the policy and the predicate only. The subject travels with the
 * caller's `evaluate` callback, exactly as the seam intends.
 */
export function privacyProbe(): PolicyProbe {
  return { policy: P1_POLICY_REF, predicate: P1_PREDICATE };
}

/**
 * One decision for one piece of content.
 *
 * Returns a `PolicyDecision` and nothing else — no action, no severity, no
 * visibility, no ordering. `asOf` is the caller's; this module reads no clock.
 */
export function evaluatePrivacy(signals: PrivacySignals, asOf: string): PolicyDecision {
  return evaluatePolicy(privacyPolicyRecord(), {
    subject: privacySubject(signals),
    predicate: P1_PREDICATE,
    asOf,
  });
}

/** Convenience: content in, decision out. Same guarantees as above. */
export function evaluatePrivacyContent(input: PrivacyDetectionInput, asOf: string): PolicyDecision {
  return evaluatePrivacy(detectPrivacySignals(input), asOf);
}
