/** The one policy this pilot covers. P2 is not implemented. */
export const P1_POLICY = 'ts.privacy.personal-information' as const;

/**
 * The versioned reference this pilot cites.
 *
 * VER-T1: "Decisions cite the version", and the provider deliberately refuses
 * to resolve a bare identity to "the latest" — guessing one would make a
 * decision record unexplainable after the fact. So the version is written here,
 * on purpose, and `privacyPolicyRecord()` fails loudly if the registry no
 * longer carries it. A corpus version bump must be a visible edit to this line,
 * never a silent re-point.
 */
export const P1_POLICY_REF = `${P1_POLICY}@1` as const;

/**
 * §9.4 `Does not govern`, verbatim, as the list this signal layer must honour:
 * already-public information in its ordinary context · self-disclosure ·
 * journalism in the public interest · business contact details · information
 * shared with consent.
 *
 * Exported so a test can assert the signal layer covers every item rather than
 * silently dropping one.
 */
export const P1_CARVE_OUTS = [
  'alreadyPublicInOrdinaryContext',
  'selfDisclosure',
  'journalismInPublicInterest',
  'subjectIsBusinessContact',
  'consentGiven',
] as const;

// ---------------------------------------------------------------------------
// The predicate — pure data, one field
// ---------------------------------------------------------------------------

/** The subject path the predicate reads. Exported so tests cannot drift from it. */
export const P1_SUBJECT_PATH = 'exposure.constituted' as const;

/**
 * The constitutive predicate.
 *
 * One comparison over one field. Every carve-out and every element of `Governs`
 * is resolved by {@link exposureConstitutedFrom} before this is evaluated, for
 * the fault-before-truth reason documented above.
 */
export const P1_PREDICATE: Expression = Object.freeze({
  op: 'eq',
  left: { ref: P1_SUBJECT_PATH },
  right: { value: true },
}) as Expression;

// ---------------------------------------------------------------------------
// Signals
// ---------------------------------------------------------------------------

/**
 * What is known about consent.
 *
 * Three states, because two would force "no evidence" to masquerade as one of
 * the answers — the exact collapse clause 3 of the freeze forbids.
 *
 * `ESTABLISHED_ABSENT` requires positive evidence that the subject did not
 * consent. **No such evidence source exists in TappyAI today**: there is no
 * report flow for reviews or posts, and the freeze forbids adding one here. So
 * in production this value is currently unreachable, and the positive path is
 * consequently unreachable — which is precisely the accepted 6/8 behaviour.
 */
export const CONSENT_EVIDENCE = ['ESTABLISHED_GIVEN', 'ESTABLISHED_ABSENT', 'NO_EVIDENCE'] as const;
export type ConsentEvidence = (typeof CONSENT_EVIDENCE)[number];

/**
 * Everything the predicate depends on.
 *
 * 🔑 `undefined` means "could not be established" and is NEVER interchangeable
 * with `false`. `false` is a finding — that the carve-out does not apply, or
 * that no identifying information is present. A detector that writes `false`
 * for something it merely did not check manufactures findings silently.
 */
export interface PrivacySignals {
  /**
   * Identifying information about a person is present in the content.
   *
   * ⚠ The extractor in this file returns `true` or `undefined`, never `false`:
   * finding no contact pattern is not the same as establishing that no
   * identifying information is present (a home address written in prose matches
   * nothing). A caller with stronger evidence may supply `false` directly.
   */
  readonly identifyingInformationPresent?: boolean;
  /** The information concerns someone other than the posting account. */
  readonly subjectIsAnotherPerson?: boolean;
  /** §9.4: business contact details. */
  readonly subjectIsBusinessContact?: boolean;
  /** §9.4: self-disclosure. */
  readonly selfDisclosure?: boolean;
  /** §9.4: already-public information in its ordinary context. */
  readonly alreadyPublicInOrdinaryContext?: boolean;
  /** §9.4: journalism in the public interest. */
  readonly journalismInPublicInterest?: boolean;
  /** §9.4: information shared with consent — and its two counterparts. */
  readonly consentEvidence?: ConsentEvidence;
}

// ---------------------------------------------------------------------------
// The constitutive question
// ---------------------------------------------------------------------------

/**
 * Is the policy constituted for this content?
 *
 * `true` / `false` / `undefined`, where `undefined` means the record does not
 * support an answer and the engine should report uncertainty.
 *
 * 🔒 FREEZE CLAUSE 3, STRUCTURALLY: there is exactly one `return true` below and
 * it is guarded by `ESTABLISHED_ABSENT`. Absent consent evidence falls to
 * `undefined`. `privacy pilot: the only path to true` in the test suite asserts
 * this exhaustively across the whole signal space, so a future edit that adds a
 * second positive path fails immediately.
 */
export function exposureConstitutedFrom(signals: PrivacySignals): boolean | undefined {
  // 1. An established carve-out settles it: nothing is constituted, so there is
  //    no exception to grant (§2.1). These are checked first because each one
  //    is decisive on its own.
  if (signals.subjectIsBusinessContact === true) return false;
  if (signals.selfDisclosure === true) return false;
  if (signals.subjectIsAnotherPerson === false) return false;
  if (signals.alreadyPublicInOrdinaryContext === true) return false;
  if (signals.journalismInPublicInterest === true) return false;
  if (signals.consentEvidence === 'ESTABLISHED_GIVEN') return false;

  // 2. Established absence of identifying information settles it too.
  if (signals.identifyingInformationPresent === false) return false;

  // 3. Not even the presence of identifying information could be established.
  if (signals.identifyingInformationPresent !== true) return undefined;

  // 4. Governed exposure is established. Consent is now decisive — §9.4 makes
  //    `Actor & target` decisive on consent and on self-disclosure versus
  //    disclosure of another.
  if (signals.consentEvidence === 'ESTABLISHED_ABSENT') return true;

  // 5. No consent evidence either way. FREEZE CLAUSE 2 and 3: uncertainty, and
  //    never a finding. This is the branch that makes the accepted result 6/8.
  return undefined;
}

/**
 * The evaluation subject.
 *
 * When the constitutive question cannot be answered the field is OMITTED, not
 * set to `null` or `false`. The engine reads an absent field as a fault and
 * reports `INSUFFICIENT_EVIDENCE`; a `false` would instead report
 * `NOT_APPLICABLE`, an affirmative finding of no violation.
 */
export function privacySubject(signals: PrivacySignals): Record<string, unknown> {
  const constituted = exposureConstitutedFrom(signals);
  return constituted === undefined ? { exposure: {} } : { exposure: { constituted } };
}

// ---------------------------------------------------------------------------
// Signal extraction — the part that reads content
// ---------------------------------------------------------------------------

/**
 * Content and the surrounding facts the platform already holds.
 *
 * 🔒 Only classified fields belong here. A like count would make the content
 * version churn on every interaction, and an author id would put identity into
 * a value that travels with the classification.
 */
export interface PrivacyDetectionInput {
  /** Body, caption and hashtags, already joined by the caller. */
  readonly text: string;
  /**
   * Contact strings the platform knows belong to the business this content is
   * about — place name, place address, and any known place contact values.
   *
   * ⚠ The Explore feed does NOT currently select place contact numbers, so in
   * production this list is usually just the name and address and the business
   * carve-out will often stay unestablished. That yields uncertainty, never a
   * finding, so the gap is safe — but it is a gap, not a solved problem.
   */
  readonly businessContactStrings?: readonly (string | null | undefined)[];
  /** Contact strings the platform knows belong to the posting account. */
  readonly authorContactStrings?: readonly (string | null | undefined)[];
  /** Supplied by an evidence source. Defaults to `NO_EVIDENCE`. */
  readonly consentEvidence?: ConsentEvidence;
  /** Supplied only where something outside this file established it. */
  readonly alreadyPublicInOrdinaryContext?: boolean;
  /** Supplied only where something outside this file established it. */
  readonly journalismInPublicInterest?: boolean;
}

/**
 * Vietnamese phone shapes, deliberately conservative.
 *
 * The digit-boundary guards are load-bearing: without the leading `(?<!\d)` a
 * price like `100.000.000đ` matches as a phone number. That could only ever
 * produce uncertainty here, never a finding — but a detector that cries wolf
 * inflates the pilot's "cannot tell" rate, which is the pilot's headline metric.
 */
const PHONE_PATTERN = /(?<!\d)(?:\+84|0)(?:[\s.\-]?\d){8,10}(?!\d)/g;
const EMAIL_PATTERN = /[A-Za-z0-9._%+\-]+@[A-Za-z0-9.\-]+\.[A-Za-z]{2,}/g;

/** Comparison form: digits and letters only, lower-cased. */
function normalise(value: string): string {
  return value.toLowerCase().replace(/[^a-z0-9]/g, '');
}

/** Every contact-shaped string in the text, in normalised comparison form. */
export function contactIdentifiersIn(text: string): string[] {
  const found = [...text.matchAll(PHONE_PATTERN), ...text.matchAll(EMAIL_PATTERN)].map((m) =>
    normalise(m[0]),
  );
  return [...new Set(found)].filter((v) => v.length > 0);
}

/**
 * Turns content into signals.
 *
 * Establishes only what the available data supports, and leaves everything else
 * `undefined`. In particular it never returns `identifyingInformationPresent:
 * false` and never returns `subjectIsBusinessContact: false` — neither absence
 * is observable from the fields the platform holds.
 */
export function detectPrivacySignals(input: PrivacyDetectionInput): PrivacySignals {
  const identifiers = contactIdentifiersIn(input.text);
  const present = identifiers.length > 0 ? true : undefined;

  const haystack = (values: readonly (string | null | undefined)[] | undefined): string =>
    (values ?? []).filter((v): v is string => typeof v === 'string').map(normalise).join(' ');

  const business = haystack(input.businessContactStrings);
  const author = haystack(input.authorContactStrings);

  const matchesBusiness = identifiers.some((id) => business.includes(id));
  const matchesAuthor = identifiers.some((id) => author.includes(id));

  return {
    ...(present === undefined ? {} : { identifyingInformationPresent: present }),
    ...(matchesBusiness ? { subjectIsBusinessContact: true } : {}),
    ...(matchesAuthor ? { selfDisclosure: true } : {}),
    ...(input.alreadyPublicInOrdinaryContext === undefined
      ? {}
      : { alreadyPublicInOrdinaryContext: input.alreadyPublicInOrdinaryContext }),
    ...(input.journalismInPublicInterest === undefined
      ? {}
      : { journalismInPublicInterest: input.journalismInPublicInterest }),
    consentEvidence: input.consentEvidence ?? 'NO_EVIDENCE',
  };
}

